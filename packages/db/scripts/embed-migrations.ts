/**
 * Embeds drizzle/*.sql into src/migrations.generated.ts so `migrate()` needs no filesystem access
 * at runtime (the web app bundles the package). Run after `drizzle-kit generate`.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, '..', 'drizzle');
const journal = JSON.parse(readFileSync(join(dir, 'meta', '_journal.json'), 'utf8')) as { entries: Array<{ tag: string; when: number }> };
const entries = journal.entries.map((e) => {
  const sql = readFileSync(join(dir, `${e.tag}.sql`), 'utf8');
  return { tag: e.tag, when: e.when, statements: sql.split('--> statement-breakpoint').map((s) => s.trim()).filter(Boolean) };
});
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).length;
if (files !== entries.length) throw new Error(`journal lists ${entries.length} migrations but ${files} .sql files exist`);
const out = `// Generated by scripts/embed-migrations.ts — do not edit.
export interface EmbeddedMigration {
  tag: string;
  when: number;
  statements: string[];
}

export const MIGRATIONS: EmbeddedMigration[] = ${JSON.stringify(entries, null, 2)};
`;
writeFileSync(join(here, '..', 'src', 'migrations.generated.ts'), out);
console.log(`embedded ${entries.length} migration(s)`);
